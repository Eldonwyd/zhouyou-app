/** 把服务端的详细进度说明压缩成“正在做什么”的短状态，例如“搜索资料中…”。
 * 服务端原文保留在接口里，页面只显示简短动作；无法识别时截短原文。
 */
const RULES: Array<[RegExp, string]> = [
  [/保存/, '保存中…'],
  [/连接/, '连接中…'],
  [/清单|打包/, '生成行前清单…'],
  [/小红书.*(?:解析|读取|提取|识图|笔记)|正在解析小红书|提取景点/, '解析小红书…'],
  [/下载本地文字识别模型/, '首次下载识字模型…'],
  [/离线识别|本地文字识别/, '本机识别文字中…'],
  [/车次|航班|时刻表/, '查询时刻与参考价…'],
  [/截图|订单|提取|识别/, '识别订单信息…'],
  [/图|照片|封面|配图/, '寻找图片…'],
  [/预算|开销|费用明细|计算/, '计算开销…'],
  [/校正|格式/, '校对行程中…'],
  [/理解问题/, '理解问题中…'],
  [/回答/, '回答中…'],
  [/修改|调整/, '修改行程中…'],
  [/时长/, '比较时长中…'],
  [/目的地/, '挑选目的地…'],
  [/安排|路线|住宿片区/, '规划行程中…'],
  [/检索|搜索|攻略|资料|核对|评价|网页/, '搜索资料中…'],
];

export function plannerShortStage(stage: string): string {
  const text = stage.trim();
  if (!text) return '处理中…';
  for (const [pattern, label] of RULES) if (pattern.test(text)) return label;
  return text.length > 10 ? `${text.slice(0, 10)}…` : text;
}
